"""Fit the mock weather generator to one real NASA POWER daily response.

Usage:
    python scripts/fit_weather_params.py path/to/power.json

Writes src/field_shift/mock/params/story_county_ia.weather.yaml (generated; the
hand-edited placeholders live in story_county_ia.yaml next to it).
Only fitted parameters are written (no raw data), each section tagged with its
provenance. Re-run this when the site changes.
"""

from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

import yaml

from field_shift import agro
from field_shift.data import power
from field_shift.mock.generators import weather

PARAMS = Path(__file__).resolve().parents[1] / "src/field_shift/mock/params/story_county_ia.weather.yaml"
HEADER = "# GENERATED by scripts/fit_weather_params.py -- do not edit by hand.\n"


def _rounded(obj):
    if isinstance(obj, float):
        return float(f"{obj:.6g}")
    if isinstance(obj, list):
        return [_rounded(v) for v in obj]
    if isinstance(obj, dict):
        return {k: _rounded(v) for k, v in obj.items()}
    return obj


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("power_json", type=Path)
    args = parser.parse_args()

    payload = json.loads(args.power_json.read_text(encoding="utf-8"))
    daily, elevation = power.parse_response(payload)
    lon, lat = payload["geometry"]["coordinates"][:2]
    fitted = weather.fit(daily)

    years = daily.groupby(daily["date"].dt.year)
    et0 = agro.et0_fao56(daily["tmax_c"], daily["tmin_c"], daily["rs_mj_m2"], daily["wind2m_m_s"],
                         agro.actual_vapour_pressure_from_rh_mean_kpa(daily["tmax_c"], daily["tmin_c"],
                                                                      daily["rh2m_pct"]),
                         lat, elevation, daily["date"].dt.day_of_year)
    targets = {
        "annual_precip_mm_mean": float(years["precip_mm"].sum().mean()),
        "annual_precip_mm_sd": float(years["precip_mm"].sum().std()),
        "annual_et0_mm_mean": float(et0.groupby(daily["date"].dt.year).sum().mean()),
        "tmax_c_mean": float(daily["tmax_c"].mean()),
        "tmin_c_mean": float(daily["tmin_c"].mean()),
        "wet_day_fraction": float((daily["precip_mm"] >= weather.WET_THRESHOLD_MM).mean()),
    }
    section = {
        "provenance": (f"fitted: NASA POWER daily point (community AG) {daily['date'].min():%Y-%m-%d}.."
                       f"{daily['date'].max():%Y-%m-%d} at lat {lat}, lon {lon}; one real response "
                       f"captured during the endpoint check; fitted {date.today().isoformat()}"),
        "elevation_m": elevation,
        "fit_targets": targets,
        **fitted,
    }
    text = yaml.safe_dump({"weather": _rounded(section)}, sort_keys=False, width=110)
    PARAMS.write_text(HEADER + text, encoding="utf-8")
    print(f"wrote weather params to {PARAMS}")
    print(json.dumps({k: round(v, 3) for k, v in targets.items()}, indent=1))


if __name__ == "__main__":
    main()
